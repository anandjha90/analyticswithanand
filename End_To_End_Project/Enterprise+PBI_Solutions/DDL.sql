CREATE OR REPLACE DATABASE PBI_DB;
CREATE OR REPLACE SCHEMA PBI_SCHEMA;

CREATE OR REPLACE FILE FORMAT CSV_FILE_FORMAT
    type = 'csv' 
    compression = 'none' 
    field_delimiter = ','
    field_optionally_enclosed_by = 'none'
    skip_header = 1 ;  

create or replace TABLE PBI_DB.PBI_SCHEMA.ATTENDANCE (
	ATTENDANCEID VARCHAR(16777216) PRIMARY KEY,
	EMPLOYEEID VARCHAR(16777216),
	DATE DATE,
	STATUS VARCHAR(16777216),
	CHECKINTIME VARCHAR(16777216),
	CHECKOUTTIME VARCHAR(16777216)
);


create or replace TABLE PBI_DB.PBI_SCHEMA.CUSTOMERS (
	CUSTOMERID VARCHAR(16777216) PRIMARY KEY,
	NAME VARCHAR(16777216),
	EMAIL VARCHAR(16777216),
	PHONE VARCHAR(16777216),
	COUNTRY VARCHAR(16777216),
	TIER VARCHAR(16777216),
	JOINDATE DATE,
	SENSITIVENOTE VARCHAR(16777216)
);

create or replace TABLE PBI_DB.PBI_SCHEMA.FEEDBACK (
	FEEDBACKID VARCHAR(16777216) PRIMARY KEY,
	CUSTOMERID VARCHAR(16777216),
	FEEDBACKDATE DATE,
	RATING NUMBER(38,0),
	COMMENTS VARCHAR(16777216),
	SENSITIVECOMMENT VARCHAR(16777216)
);

create or replace TABLE PBI_DB.PBI_SCHEMA.HR (
	EMPLOYEEID VARCHAR(16777216) PRIMARY KEY,
	NAME VARCHAR(16777216),
	DEPARTMENT VARCHAR(16777216),
	ROLE VARCHAR(16777216),
	SALARY NUMBER(38,2),
	JOINDATE DATE,
	MANAGEREMAIL VARCHAR(16777216),
	SENSITIVEHRNOTE VARCHAR(16777216)
);

create or replace TABLE PBI_DB.PBI_SCHEMA.ORDERS (
	ORDERID VARCHAR(16777216) PRIMARY KEY,
	CUSTOMERID VARCHAR(16777216),
	PRODUCTID VARCHAR(16777216),
	ORDERDATE DATE,
	QUANTITY NUMBER(38,0),
	TOTALAMOUNT NUMBER(38,2),
	REGION VARCHAR(16777216),
	REMARKS VARCHAR(16777216)
);


create or replace TABLE PBI_DB.PBI_SCHEMA.PRODUCTS (
	PRODUCTID VARCHAR(16777216) PRIMARY KEY,
	PRODUCTNAME VARCHAR(16777216),
	CATEGORY VARCHAR(16777216),
	UNITPRICE NUMBER(38,2),
	STOCKAVAILABLE NUMBER(38,0),
	SUPPLIER VARCHAR(16777216),
	SENSITIVEPRODUCTINFO VARCHAR(16777216)
);
