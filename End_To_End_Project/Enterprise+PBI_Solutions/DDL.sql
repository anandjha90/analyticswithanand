
create warehouse DEMOWAREHOUSE;
create database DEMODATABASE;
create schema DEMOSCHEMA;


create or replace TABLE DEMODATABASE.DEMOSCHEMA.ATTENDANCE (
	ATTENDANCEID VARCHAR(16777216),
	EMPLOYEEID VARCHAR(16777216),
	DATE DATE,
	STATUS VARCHAR(16777216),
	CHECKINTIME VARCHAR(16777216),
	CHECKOUTTIME VARCHAR(16777216)
);


create or replace TABLE DEMODATABASE.DEMOSCHEMA.CUSTOMERS (
	CUSTOMERID VARCHAR(16777216),
	NAME VARCHAR(16777216),
	EMAIL VARCHAR(16777216),
	PHONE VARCHAR(16777216),
	COUNTRY VARCHAR(16777216),
	TIER VARCHAR(16777216),
	JOINDATE DATE,
	SENSITIVENOTE VARCHAR(16777216)
);

create or replace TABLE DEMODATABASE.DEMOSCHEMA.FEEDBACK (
	FEEDBACKID VARCHAR(16777216),
	CUSTOMERID VARCHAR(16777216),
	FEEDBACKDATE DATE,
	RATING NUMBER(38,0),
	COMMENTS VARCHAR(16777216),
	SENSITIVECOMMENT VARCHAR(16777216)
);

create or replace TABLE DEMODATABASE.DEMOSCHEMA.HR (
	EMPLOYEEID VARCHAR(16777216),
	NAME VARCHAR(16777216),
	DEPARTMENT VARCHAR(16777216),
	ROLE VARCHAR(16777216),
	SALARY NUMBER(38,2),
	JOINDATE DATE,
	MANAGEREMAIL VARCHAR(16777216),
	SENSITIVEHRNOTE VARCHAR(16777216)
);

create or replace TABLE DEMODATABASE.DEMOSCHEMA.ORDERS (
	ORDERID VARCHAR(16777216),
	CUSTOMERID VARCHAR(16777216),
	PRODUCTID VARCHAR(16777216),
	ORDERDATE DATE,
	QUANTITY NUMBER(38,0),
	TOTALAMOUNT NUMBER(38,2),
	REGION VARCHAR(16777216),
	REMARKS VARCHAR(16777216)
);


create or replace TABLE DEMODATABASE.DEMOSCHEMA.PRODUCTS (
	PRODUCTID VARCHAR(16777216),
	PRODUCTNAME VARCHAR(16777216),
	CATEGORY VARCHAR(16777216),
	UNITPRICE NUMBER(38,2),
	STOCKAVAILABLE NUMBER(38,0),
	SUPPLIER VARCHAR(16777216),
	SENSITIVEPRODUCTINFO VARCHAR(16777216)
);
